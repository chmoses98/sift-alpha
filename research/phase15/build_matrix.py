"""Phase 15: build the market-by-market Data Readiness Matrix and the Predictive Confidence Matrix (research only).

    python research/phase15/build_matrix.py [--vault ../sift-data-vault] [--today 2026-11-18]

Inputs (all in research/phase15/): kalshi_game_market_universe.json (verified listings + settlement rules from the vault's
official settlement snapshot), readiness/<SPORT>.json and matrix/<SPORT>.json written by each sport workstream.
Outputs: docs/PHASE15_DATA_READINESS_MATRIX.md, docs/PHASE15_PREDICTIVE_CONFIDENCE_MATRIX.md, research/phase15/matrix_combined.json,
research/phase15/data_checks.json. Reads no prices; changes nothing in production.
"""
from __future__ import annotations

import argparse
import json
import re
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SPORTS = ("NBA", "CFB", "CBB", "NHL", "NFL", "MLB")
SPORT_SEASON_END = {"NBA": "2027-06", "CBB": "2027-04", "NHL": "2027-06", "CFB": "2027-01", "NFL": "2027-02", "MLB": "2026-11"}
IN_SEASON = {"NBA": True, "CBB": True, "NHL": True, "CFB": True, "NFL": True, "MLB": False}   # on 2026-11-18


def _load(p: Path, default):
    try:
        return json.loads(p.read_text())
    except (OSError, json.JSONDecodeError):
        return default


def data_checks(vault: Path, universe: dict, today: date) -> dict:
    """Freshness, completeness and provenance checks over the vault catalog and the Kalshi listing universe."""
    cat = _load(vault / "CATALOG.json", {})
    out = {"generated_for": str(today), "vault": [], "kalshi_series_staleness": [], "failures": []}
    for a in cat.get("archives", []):
        sport, ds, season = a.get("sport"), a.get("dataset"), str(a.get("season"))
        retrieved = a.get("retrieved") or (a.get("created_utc") or "")[:10]
        age = (today - date.fromisoformat(retrieved)).days if re.match(r"\d{4}-\d{2}-\d{2}", retrieved or "") else None
        last_season = max([int(x) for x in re.findall(r"\d{4}", season)] or [0])
        prov_ok = bool(a.get("origin")) and bool(a.get("rights"))
        stale = IN_SEASON.get(sport, False) and age is not None and age > 7 and last_season >= 2026
        row = {"sport": sport, "dataset": ds, "season": season, "version": a.get("version"), "retrieved": retrieved, "age_days": age,
               "provenance_recorded": prov_ok, "in_season_refresh_due": bool(stale)}
        out["vault"].append(row)
        if not prov_ok:
            out["failures"].append(f"{sport}/{ds}/{season}: origin or rights missing")
    for sport, series in universe.get("series", {}).items():
        for s, v in series.items():
            last = v.get("last") or "0000-00-00"
            try:
                gap = (today - date.fromisoformat(last)).days
            except ValueError:
                gap = None
            listed_now = gap is not None and gap <= 14
            out["kalshi_series_staleness"].append({"sport": sport, "series": s, "last_settled": last, "days_since": gap,
                                                   "listed_recently": listed_now, "in_season": IN_SEASON.get(sport)})
    return out


def readiness_md(rows: list[dict], universe: dict, checks: dict) -> str:
    L = ["# Phase 15 Data Readiness Matrix (market-by-market)", "",
         "Generated by `research/phase15/build_matrix.py` from the sport workstreams' `readiness/<SPORT>.json`, the verified Kalshi",
         "listing universe (`kalshi_game_market_universe.json`, official settlements snapshot 2026-11-16) and vault catalog checks.",
         "Readiness is tracked separately for historical training, current pregame prediction and official settlement.", ""]
    by = {}
    for r in rows:
        by.setdefault(r["sport"], []).append(r)
    for sp in SPORTS:
        rs = by.get(sp, [])
        n_series = len(universe.get("series", {}).get(sp, {}))
        n_mk = sum(v["markets"] for v in universe.get("series", {}).get(sp, {}).values())
        L += [f"## {sp}", "", f"Kalshi game/period series with settled markets: {n_series} ({n_mk:,} settled contracts).", ""]
        if not rs:
            L += ["_No readiness rows submitted._", ""]
            continue
        L += ["| family | status | history | pregame | settlement | acquired this phase | top missing input (source / blocker) |", "|---|---|---|---|---|---|---|"]
        for r in rs:
            miss = r.get("missing_inputs") or []
            m0 = f"{miss[0]['input']} ({miss[0].get('best_free_source', '')} / {miss[0].get('blocker', '')})" if miss else "-"
            acq = "; ".join(r.get("acquired_this_phase") or []) or "-"
            L.append(f"| {r['family']} | **{r.get('status', '?')}** | {r.get('historical_depth', '')} | {r.get('pregame_ready', '')} | "
                     f"{r.get('settlement_ready', '')} | {acq} | {m0} |")
        L.append("")
        for r in rs:
            L.append(f"<details><summary>{r['family']}: inputs</summary>\n")
            L.append(f"- Kalshi series: {', '.join(r.get('kalshi_series') or [])}")
            L.append(f"- Available: {'; '.join(r.get('inputs_available') or [])}")
            L.append(f"- Used in production: {'; '.join(r.get('inputs_used_in_production') or [])}")
            L.append(f"- Collected but unused: {'; '.join(r.get('inputs_collected_unused') or [])}")
            for m in r.get("missing_inputs") or []:
                L.append(f"- Missing: **{m['input']}** - source: {m.get('best_free_source', '')}; blocker: {m.get('blocker', '')}")
            L.append("\n</details>\n")
    stale = [c for c in checks["kalshi_series_staleness"] if c["in_season"] and not c["listed_recently"] and (c["days_since"] or 0) < 400]
    L += ["## Automated checks", "",
          f"- Vault archives checked: {len(checks['vault'])}; provenance failures: {len(checks['failures'])}"
          + (" (" + "; ".join(checks["failures"]) + ")" if checks["failures"] else ""),
          f"- In-season datasets older than 7 days (refresh due): "
          + (", ".join(f"{v['sport']}/{v['dataset']}/{v['season']} ({v['age_days']} d)" for v in checks["vault"] if v["in_season_refresh_due"]) or "none"),
          f"- In-season Kalshi series with no settlement in the last 14 days (possibly delisted): "
          + (", ".join(f"{c['series']} (last {c['last_settled']})" for c in stale) or "none"), ""]
    return "\n".join(L)


def confidence_md(rows: list[dict]) -> str:
    order = {"RELIABLE": 0, "USABLE": 1, "ABSTAIN": 2}
    L = ["# Phase 15 Predictive Confidence Matrix", "",
         "One row per sport x market family x segment, from `matrix/<SPORT>.json`. Verdicts: RELIABLE = calibrated (slope ~0.85-1.15)",
         "and better than the stated baseline with CI excluding 0 (or equal to a strong baseline); USABLE = calibrated but no demonstrated",
         "gain, or a gain with mild miscalibration; ABSTAIN = miscalibrated, unstable, low signal, too little data or not listed.",
         "These are forecast-quality verdicts for independent outcome probabilities, not claims of betting edge.", ""]
    for v in ("RELIABLE", "USABLE", "ABSTAIN"):
        rs = sorted([r for r in rows if r["verdict"] == v], key=lambda r: (r["sport"], r["segment"], r["family"]))
        L += [f"## {v} ({len(rs)})", "", "| sport | family | segment | model | baseline | n games | drivers | notes |", "|---|---|---|---|---|---|---|---|"]
        for r in rs:
            L.append(f"| {r['sport']} | {r['family']} | {r['segment']} | {r['model']} | {r['baseline']} | {r['n_games']} | "
                     f"{', '.join(r.get('drivers') or [])} | {r.get('notes', '')} |")
        L.append("")
    del order
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--vault", default=str(ROOT.parent / "sift-data-vault"))
    ap.add_argument("--today", default=str(date.today()))
    a = ap.parse_args()
    today = date.fromisoformat(a.today)
    uni = _load(HERE / "kalshi_game_market_universe.json", {})
    ready = [r for sp in SPORTS for r in _load(HERE / "readiness" / f"{sp}.json", [])]
    conf = [r for sp in SPORTS for r in _load(HERE / "matrix" / f"{sp}.json", [])]
    checks = data_checks(Path(a.vault), uni, today)
    (HERE / "data_checks.json").write_text(json.dumps(checks, indent=1))
    (HERE / "matrix_combined.json").write_text(json.dumps({"readiness": ready, "confidence": conf}, indent=1, default=float))
    (ROOT / "docs" / "PHASE15_DATA_READINESS_MATRIX.md").write_text(readiness_md(ready, uni, checks))
    (ROOT / "docs" / "PHASE15_PREDICTIVE_CONFIDENCE_MATRIX.md").write_text(confidence_md(conf))
    print(json.dumps({"readiness_rows": len(ready), "confidence_rows": len(conf), "vault_archives": len(checks["vault"]),
                      "provenance_failures": len(checks["failures"])}))


if __name__ == "__main__":
    main()
